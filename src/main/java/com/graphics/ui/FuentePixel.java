    private FuentePixel() {
    }

    private static void g(char caracter, String... filas) {
        GLIFOS.put(caracter, filas);
    }

    /** Mayúsculas y sin tildes, para que todo texto tenga glifo (por ejemplo "Cámara" -> "CAMARA"). */
    public static String normalizar(String texto) {
        String sinTildes = Normalizer.normalize(texto, Normalizer.Form.NFD).replaceAll("\\p{M}", "");
        return sinTildes.toUpperCase(Locale.ROOT);
    }

    /** ¿Está encendido el píxel (fila, columna) del carácter? Los caracteres desconocidos se dibujan como '?'. */
    public static boolean pixel(char caracter, int fila, int columna) {
        String[] glifo = GLIFOS.getOrDefault(caracter, GLIFOS.get('?'));
        return glifo[fila].charAt(columna) == '#';
    }

    /** Ancho del texto en píxeles de fuente (sin la separación final). */
    public static int ancho(String texto) {
        return texto.isEmpty() ? 0 : texto.length() * AVANCE - 1;
    }
